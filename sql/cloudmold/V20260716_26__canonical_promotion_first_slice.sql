CREATE TABLE cloudmold_promotion_advertising_interaction (
    interaction_id VARCHAR(64) NOT NULL,
    tenant_id BIGINT NOT NULL,
    deduplication_key VARCHAR(128) NOT NULL,
    interaction_type VARCHAR(24) NOT NULL,
    placement_id VARCHAR(64) NOT NULL,
    campaign_id VARCHAR(64) NOT NULL,
    principal_id VARCHAR(64) NULL,
    session_id VARCHAR(128) NULL,
    source_interaction_id VARCHAR(64) NULL,
    order_ref VARCHAR(128) NULL,
    attribution_amount_minor BIGINT NULL,
    currency_code CHAR(3) NULL,
    occurred_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (interaction_id),
    UNIQUE KEY uk_promotion_interaction_tenant_dedup (tenant_id, deduplication_key),
    KEY idx_promotion_interaction_placement_time (tenant_id, placement_id, occurred_at),
    KEY idx_promotion_interaction_source (tenant_id, source_interaction_id),
    CONSTRAINT ck_promotion_attribution_amount CHECK (attribution_amount_minor IS NULL OR attribution_amount_minor >= 0)
) ENGINE=InnoDB;
