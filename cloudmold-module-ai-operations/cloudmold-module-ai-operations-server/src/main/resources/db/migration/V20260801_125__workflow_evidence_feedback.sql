CREATE TABLE cloudmold_ai_ops_external_evidence_snapshot (
    snapshot_id VARCHAR(64) NOT NULL,
    tenant_id BIGINT NOT NULL,
    lineage_id VARCHAR(128) NOT NULL,
    workflow_id VARCHAR(191) NOT NULL,
    workflow_version VARCHAR(64) NOT NULL,
    proposal_id VARCHAR(64) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    source_class VARCHAR(32) NOT NULL,
    url VARCHAR(512) NOT NULL,
    published_at DATETIME(6) NULL,
    fetched_at DATETIME(6) NOT NULL,
    summary_text TEXT NOT NULL,
    content_hash_sha256 CHAR(64) NOT NULL,
    confidence DECIMAL(5, 4) NOT NULL,
    region VARCHAR(128) NULL,
    applicability VARCHAR(191) NULL,
    severity VARCHAR(16) NOT NULL,
    dqc_status VARCHAR(32) NOT NULL,
    record_status VARCHAR(32) NOT NULL,
    fresh_until DATETIME(6) NULL,
    window_start DATETIME(6) NOT NULL,
    window_end DATETIME(6) NOT NULL,
    release_eligible TINYINT(1) NOT NULL DEFAULT 0,
    actor_subject VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (snapshot_id),
    UNIQUE KEY uk_ai_ops_external_snapshot_hash (tenant_id, workflow_id, content_hash_sha256, fetched_at),
    KEY idx_ai_ops_external_snapshot_tenant_workflow_window (tenant_id, workflow_id, window_start, window_end),
    CONSTRAINT ck_ai_ops_external_source_type CHECK (source_type IN ('EXTERNAL_WEB')),
    CONSTRAINT ck_ai_ops_external_source_class CHECK (source_class IN ('NEWS', 'REGULATION', 'MARKETPLACE', 'SOCIAL', 'VENDOR_DOC', 'THIRD_PARTY_ANALYSIS')),
    CONSTRAINT ck_ai_ops_external_confidence CHECK (confidence >= 0 AND confidence <= 1),
    CONSTRAINT ck_ai_ops_external_severity CHECK (severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_ai_ops_external_dqc CHECK (dqc_status IN ('PASS', 'WARN', 'FAIL', 'UNKNOWN', 'NOT_APPLICABLE')),
    CONSTRAINT ck_ai_ops_external_status CHECK (record_status IN ('CAPTURED', 'VERIFIED', 'STALE', 'REJECTED')),
    CONSTRAINT ck_ai_ops_external_window CHECK (window_end >= window_start),
    CONSTRAINT ck_ai_ops_external_fresh CHECK (fresh_until IS NULL OR fresh_until >= window_end),
    CONSTRAINT ck_ai_ops_external_redline CHECK (release_eligible = 0)
);
